#!/bin/bash

OUTDIR="results/false-positive"
RESULTS="$OUTDIR/false-positive-results.csv"

APPROVED="10.10.2.2"
RESTRICTED="10.10.2.3"

mkdir -p "$OUTDIR"
echo "trial,authorized_observed,authorized_success,restricted_detected,false_positive" > "$RESULTS"

echo "========================================"
echo "False-Positive Experiment"
echo "Authorized destination: $APPROVED"
echo "Restricted destination: $RESTRICTED"
echo "Trials: 10"
echo "========================================"

for TRIAL in $(seq 1 10); do

    echo
    echo "Running trial $TRIAL..."

    CAPTURE="/results/false_positive_capture.txt"

    # Capture HTTP traffic generated by the agent.
    docker exec security-gateway sh -c \
        "rm -f $CAPTURE; tcpdump -tt -l -n -i any 'src host 10.10.1.2 and tcp dst port 80' > $CAPTURE 2>/dev/null" &

    TCPDUMP_PID=$!

    sleep 1

    CODE=$(docker exec agent curl --max-time 3 -s -o /dev/null \
        -w "%{http_code}" "http://${APPROVED}")

    sleep 1

    docker exec security-gateway pkill tcpdump 2>/dev/null || true
    wait "$TCPDUMP_PID" 2>/dev/null || true

    HOST_CAPTURE="$OUTDIR/trial_${TRIAL}_capture.txt"
    docker cp security-gateway:$CAPTURE "$HOST_CAPTURE" >/dev/null

    if grep -q "10.10.1.2.*> ${APPROVED}.80" "$HOST_CAPTURE"; then
        AUTHORIZED_OBSERVED="YES"
    else
        AUTHORIZED_OBSERVED="NO"
    fi

    if [ "$CODE" = "200" ]; then
        AUTHORIZED_SUCCESS="YES"
    else
        AUTHORIZED_SUCCESS="NO"
    fi

    if grep -q "10.10.1.2.*> ${RESTRICTED}.80" "$HOST_CAPTURE"; then
        RESTRICTED_DETECTED="YES"
        FALSE_POSITIVE="YES"
    else
        RESTRICTED_DETECTED="NO"
        FALSE_POSITIVE="NO"
    fi

    echo "$TRIAL,$AUTHORIZED_OBSERVED,$AUTHORIZED_SUCCESS,$RESTRICTED_DETECTED,$FALSE_POSITIVE" >> "$RESULTS"

    echo "Authorized observed: $AUTHORIZED_OBSERVED"
    echo "Authorized success:  $AUTHORIZED_SUCCESS"
    echo "Restricted detected: $RESTRICTED_DETECTED"
    echo "False positive:      $FALSE_POSITIVE"

done

echo
echo "========================================"
echo "False-positive experiment complete."
echo "Results: $RESULTS"
echo "========================================"
